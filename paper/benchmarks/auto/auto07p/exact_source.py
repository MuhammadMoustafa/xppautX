#!/usr/bin/env -S uv run --locked python
"""W459 (#522): AUTO-07p's equation file in C with the model's exact derivatives (JAC = 1), generated from the model.

py_s1bf.c, the hand-written one, is PY_S1Bf's. This is the same for any model tools/auto_reference.py translates: it
reads the expanded right-hand side the way that module's Fortran FUNC does (`Equations.expand`, `conditionals`,
`ordered_assigns`) and differentiates it by forward mode over the model's own formulas, the chain rule applied
only where a derivative is not zero: DFDU(i, j) = d f_i / d u_j, and DFDP(i, k) = d f_i / d PAR(k) for the
parameters the description's runs continue. The code is straight-line, one temporary per operation, as a hand
derivation would be; nothing is differenced. `if C then A else B` differentiates the branch taken (C has none).

`check` compares every derivative with central differences (Richardson-extrapolated) at the start and at three
points off it, and the C right-hand side with the Fortran one's values.
"""
import json
from pathlib import Path
import re
import subprocess

from odex_model import Refused

DERIVATIVE_TOLERANCE = 1e-6  # of the check, relative to the larger of 1 and the derivative (tests/test_exact_jacobian.cpp's)
FUNCTIONS = {'exp': 'exp', 'tanh': 'tanh', 'abs': 'fabs'}  # the functions the translated models differentiate through
COMPARISONS = ('<', '<=', '>', '>=', '==', '!=')
HEADER = '''/* generated by exact_source.py from the model's right-hand side: the exact derivatives of the Fortran FUNC of
 * tools/auto_reference.py (ijac 1: DFDU; ijac 2: DFDU and the DFDP columns of the continued parameters) */
#include "auto_f2c.h"
#include <math.h>
'''
STUBS = '''int bcnd(integer ndim, const doublereal *par, const integer *icp, integer nbc, const doublereal *u0,
         const doublereal *u1, integer ijac, doublereal *fb, doublereal *dbc) { return 0; }
int icnd(integer ndim, const doublereal *par, const integer *icp, integer nint, const doublereal *u,
         const doublereal *uold, const doublereal *udot, const doublereal *upold, integer ijac,
         doublereal *fi, doublereal *dint) { return 0; }
int fopt(integer ndim, const doublereal *u, const integer *icp, const doublereal *par, integer ijac,
         doublereal *fs, doublereal *dfdu, doublereal *dfdp) { return 0; }
int pvls(integer ndim, const doublereal *u, doublereal *par) { return 0; }
'''
# the check's driver: the equation file's own FUNC at the start and at points off it (each state's own factor)
DRIVER = r'''
#include <stdio.h>
enum { N = %(n)d, NPAR = %(npar)d, POINTS = 4 };
static const integer SLOTS[] = {%(slots)s};
static void evaluate(double *u, double *par, double *f) { integer icp[2] = {1, 11}; func(N, u, icp, par, 0, f, 0, 0); }
int main(void)
{
  static double start[N], u[N], par[NPAR], f[N], g[N], fp[N], fm[N], fp2[N], fm2[N], dfdu[N * N], dfdp[N * NPAR], dfdu1[N * N];
  integer icp[2] = {1, 11};
  stpnt(N, 0, start, par);
  for (int k = 0; k < POINTS; ++k) {
    for (int i = 0; i < N; ++i) u[i] = start[i] * (1 + (k ? 0.05 * (k %% 2 ? 1 : -1) * sin(1.0 + i + k) : 0.0));
    func(N, u, icp, par, 2, f, dfdu, dfdp);
    func(N, u, icp, par, 1, g, dfdu1, 0);
    double same = 0, worst = 0, worst_p = 0;
    int wi = 0, wj = 0;
    evaluate(u, par, fp);
    for (int i = 0; i < N; ++i) same = fmax(same, fmax(fabs(fp[i] - f[i]), fabs(g[i] - f[i])));
    for (int i = 0; i < N * N; ++i) same = fmax(same, fabs(dfdu1[i] - dfdu[i]));
    for (int j = 0; j < N + (int)(sizeof SLOTS / sizeof *SLOTS); ++j) {
      double *x = j < N ? &u[j] : &par[SLOTS[j - N] - 1];
      const double keep = *x, h = fmax(1e-3 * fabs(keep), 1e-8);
      *x = keep + h; evaluate(u, par, fp);
      *x = keep - h; evaluate(u, par, fm);
      *x = keep + 2 * h; evaluate(u, par, fp2);
      *x = keep - 2 * h; evaluate(u, par, fm2);
      *x = keep;
      for (int i = 0; i < N; ++i) {
        const double d1 = (fp[i] - fm[i]) / (2 * h), d2 = (fp2[i] - fm2[i]) / (4 * h);
        const double fd = (4 * d1 - d2) / 3, exact = j < N ? dfdu[i + N * j] : dfdp[i + N * (SLOTS[j - N] - 1)];
        const double rel = fabs(fd - exact) / fmax(1.0, fabs(exact));
        if (j >= N && !(rel <= worst_p)) worst_p = rel;
        if (!(rel <= worst)) { worst = rel; wi = i; wj = j; }
      }
    }
    printf("{\"point\": %%d, \"worst_relative_error\": %%.3e, \"worst_parameter_error\": %%.3e, \"at\": [%%d, %%d], \"ijac_difference\": %%.3e, \"f\": [", k, worst, worst_p, wi, wj, same);
    for (int i = 0; i < N; ++i) printf("%%s%%.17g", i ? ", " : "", f[i]);
    printf("]}\n");
  }
  return 0;
}
'''


def product(a, b):
    return b if a == '1.0' else a if b == '1.0' else '%s*%s' % (a, b)


class Differentiator:
    """Reads the model's formulas and gives each operation's value and derivatives as (C name, {variable: C name}):
    the variables are ('u', i) for a state and ('p', slot) for a continued parameter, and an operation that does not
    depend on one has no entry for it. With `derive` off only the values are computed."""
    def __init__(self, eqs, slots, derive):
        self.eqs, self.slots, self.derive = eqs, slots, derive
        self.lines, self.quantity, self.count = [], {}, 0

    def equations(self):
        """The lines that compute the quantities and equations, and each equation's (value, derivatives)."""
        for name, toks in self.eqs.ordered_assigns():
            self.quantity[name] = self.read(toks)
        return [self.read(self.eqs.o.odes[s]) for s in self.eqs.o.states]

    def read(self, toks):
        self.toks, self.pos = self.eqs.conditionals(self.eqs.expand(toks)), 0
        x = self.expression()
        if self.pos != len(self.toks):
            raise Refused('expression not understood from %s: %s' % (self.toks[self.pos], ' '.join(self.toks)))
        return x

    def temp(self, expression, kind='double'):
        name = 't%d' % self.count
        self.count += 1
        self.lines.append('  const %s %s = %s;' % (kind, name, expression))
        return name

    def peek(self):
        return self.toks[self.pos] if self.pos < len(self.toks) else None

    def take(self):
        self.pos += 1
        return self.toks[self.pos - 1]

    def variables(self, x, y):
        return sorted(x[1].keys() | y[1].keys()) if self.derive else []

    def expression(self):
        x = self.term()
        while self.peek() in ('+', '-'):
            op = self.take()
            y = self.term()
            d = {}
            for k in self.variables(x, y):
                a, b = x[1].get(k), y[1].get(k)
                d[k] = self.temp('%s %s %s' % (a, op, b)) if a and b else a if a else self.temp('-' + b) if op == '-' else b
            x = self.temp('%s %s %s' % (x[0], op, y[0])), d
        return x

    def term(self):
        x = self.factor()
        while self.peek() in ('*', '/'):
            op = self.take()
            y = self.factor()
            v = self.temp('%s %s %s' % (x[0], op, y[0]))
            d = {}
            for k in self.variables(x, y):
                a, b = x[1].get(k), y[1].get(k)
                if op == '*':
                    d[k] = self.temp(' + '.join(([product(a, y[0])] if a else []) + ([product(x[0], b)] if b else [])))
                elif a and b:
                    d[k] = self.temp('(%s - %s*%s)/%s' % (a, v, b, y[0]))
                else:
                    d[k] = self.temp('%s/%s' % (a, y[0]) if a else '-%s*%s/%s' % (v, b, y[0]))
            x = v, d
        return x

    def factor(self):
        """A sign binds looser than a power (Fortran's -a**2 is -(a**2)); a power's exponent is a factor, from the right."""
        if self.peek() in ('-', '+'):
            sign = self.take()
            x = self.factor()
            return (self.temp('-' + x[0]), {k: self.temp('-' + v) for k, v in x[1].items()}) if sign == '-' else x
        x = self.primary()
        if self.peek() != '^':
            return x
        self.take()
        return self.power(x, self.factor())

    def power(self, x, y):
        v = self.temp('pow(%s, %s)' % (x[0], y[0]))
        d = {}
        # n*x^(n-1)*dx for an exponent that is a constant; the general rule when a continued parameter is in it
        slope = self.temp('%s*pow(%s, %s - 1.0)' % (y[0], x[0], y[0])) if self.derive and x[1] and not y[1] else None
        for k in self.variables(x, y):
            a, b = x[1].get(k), y[1].get(k)
            terms = ([f'{b}*log({x[0]})'] if b else []) + ([f'{y[0]}*{a}/{x[0]}'] if a else [])
            d[k] = self.temp(product(slope, a)) if slope else self.temp('%s*(%s)' % (v, ' + '.join(terms)))
        return v, d

    def primary(self):
        t = self.take()
        if t == '(':
            x = self.expression()
            if self.take() != ')':
                raise Refused('unbalanced parentheses')
            return x
        if re.fullmatch(r'\d+\.?\d*(?:[eE][+-]?\d+)?|\.\d+(?:[eE][+-]?\d+)?', t):
            return (t + '.0' if t.isdigit() else t), {}
        if t == 'pi':
            return '3.141592653589793', {}
        if t in self.eqs.o.states:
            i = self.eqs.o.states.index(t)
            return 'u[%d]' % i, {('u', i): '1.0'}
        if t in self.eqs.slot:
            slot = self.eqs.slot[t]
            return 'par[%d]' % (slot - 1), ({('p', slot): '1.0'} if slot in self.slots and self.derive else {})
        if t in self.eqs.locals:
            return self.quantity[t]
        if self.peek() == '(':
            return self.call(t)
        raise Refused('unknown name in the equations: ' + t)

    def arguments(self, comparison):
        """The arguments of a call, to its ')'. With `comparison` the third is `a < b`, only a value."""
        self.take()
        args = []
        while True:
            last = comparison and len(args) == 2
            derive, self.derive = self.derive, self.derive and not last
            x = self.expression()
            if last:
                if self.peek() not in COMPARISONS:
                    raise Refused('only `if COMPARISON then A else B` is differentiated')
                op = self.take()
                x = self.temp('%s %s %s' % (x[0], op, self.expression()[0]), 'int'), {}
            self.derive = derive
            args.append(x)
            if self.take() == ')':
                return args

    def select(self, condition, then, other):
        """`condition ? then : other`, and the derivatives of the one taken."""
        d = {k: self.temp('%s ? %s : %s' % (condition, then[1].get(k, '0.0'), other[1].get(k, '0.0'))) for k in self.variables(then, other)}
        return self.temp('%s ? %s : %s' % (condition, then[0], other[0])), d

    def call(self, name):
        if name == 'MERGE':
            then, other, condition = self.arguments(True)
            return self.select(condition[0], then, other)
        if name in ('max', 'min'):
            a, b = self.arguments(False)
            return self.select(self.temp('%s %s %s' % (a[0], '>' if name == 'max' else '<', b[0]), 'int'), a, b)
        if name not in FUNCTIONS:
            raise Refused('the derivative of %s is not generated: no translated model needs it yet' % name)
        x, = self.arguments(False)
        v = self.temp('%s(%s)' % (FUNCTIONS[name], x[0]))
        if not self.derive:
            return v, {}
        if name == 'abs':  # the derivative of x itself or its negative, by the sign of x
            return v, {k: self.temp('%s < 0.0 ? -%s : %s' % (x[0], b, b)) for k, b in x[1].items()}
        slope = v if name == 'exp' else self.temp('1.0 - %s*%s' % (v, v))
        return v, {k: self.temp(product(slope, b)) for k, b in x[1].items()}


def source(eqs, start, d):
    """The C text of the equation file of `eqs` (auto_reference.Equations) at the state `start`; the runs of the
    description `d` name the parameters whose derivatives (DFDP) it gives."""
    names = {n for r in d['runs'] for n in (r['parameters'] if 'parameters' in r else [r['parameter']])}
    slots = {eqs.slot[n] for n in names}
    values, exact = Differentiator(eqs, slots, False), Differentiator(eqs, slots, True)
    plain, derived = values.equations(), exact.equations()
    out = [HEADER, 'int func(integer ndim, const doublereal *u, const integer *icp, const doublereal *par, integer ijac,',
           '         doublereal *f, doublereal *dfdu, doublereal *dfdp)', '{', '  if (ijac == 0) {', *values.lines]
    out += ['  f[%d] = %s;' % (i, v) for i, (v, _) in enumerate(plain)] + ['  return 0;', '  }', '  {', *exact.lines]
    out += ['  f[%d] = %s;' % (i, v) for i, (v, _) in enumerate(derived)]
    out += ['  for (integer k = 0; k < ndim * ndim; ++k) dfdu[k] = 0.0;']
    out += ['  dfdu[%d + ndim*%d] = %s;' % (i, k[1], v) for i, (_, ds) in enumerate(derived) for k, v in ds.items() if k[0] == 'u']
    out += ['  if (ijac == 1) return 0;', '  for (integer k = 0; k < ndim * %d; ++k) dfdp[k] = 0.0;' % max(slots)]
    out += ['  dfdp[%d + ndim*%d] = %s;' % (i, k[1] - 1, v) for i, (_, ds) in enumerate(derived) for k, v in ds.items() if k[0] == 'p']
    out += ['  return 0;', '  }', '}', '', 'int stpnt(integer ndim, doublereal t, doublereal *u, doublereal *par)', '{']
    out += ['  par[%d] = %r;' % (slot - 1, float(eqs.values[name])) for name, slot in eqs.slot.items()]
    out += ['  u[%d] = %r;' % (i, float(v)) for i, v in enumerate(start)] + ['  return 0;', '}', '', STUBS]
    return '\n'.join(out)


def check(text, eqs, d, folder, auto_dir, rhs=None):
    """Compiles `text` with a driver and compares its derivatives with central differences (Richardson), at the start and at
    three points off it: {'worst_relative_error': ..., 'points': [...], 'passed': ...}; with `rhs` (tools/auto_reference.py's
    check_rhs result for the same start) also the C right-hand side's values with the Fortran one's, as that check does."""
    folder.mkdir(parents=True, exist_ok=True)
    n = len(eqs.o.states)
    names = {name for r in d['runs'] for name in (r['parameters'] if 'parameters' in r else [r['parameter']])}
    slots = sorted({eqs.slot[name] for name in names})
    (folder / 'exact.c').write_text(text)
    (folder / 'exact_check.c').write_text('#include "exact.c"\n' + DRIVER % dict(n=n, npar=max(eqs.npar, 36), slots=', '.join(map(str, slots))))
    subprocess.run(['gcc', '-std=gnu17', '-O1', '-ffp-contract=off', '-I', str(Path(auto_dir) / 'include'), 'exact_check.c', '-lm', '-o', 'exact_check'],
                   cwd=folder, check=True, capture_output=True, text=True)
    points = [json.loads(line) for line in subprocess.run([str((folder / 'exact_check').resolve())], cwd=folder, check=True,
                                                         capture_output=True, text=True).stdout.splitlines()]
    result = dict(parameters=sorted(names), states=n, points=points, tolerance=DERIVATIVE_TOLERANCE,
                  worst_relative_error=max(p['worst_relative_error'] for p in points),
                  worst_parameter_error=max(p['worst_parameter_error'] for p in points),
                  where=['d f_%s / d %s' % (eqs.o.states[p['at'][0]], eqs.o.states[p['at'][1]] if p['at'][1] < n else sorted(names)[p['at'][1] - n]) for p in points])
    # the first point is the start: the C values against the Fortran's, relative to the sizes of the terms as check_rhs does
    if rhs:
        result['rhs_relative_errors'] = [abs(a - b) / s if s else float(a != b) for a, b, s in zip(points[0]['f'], rhs['fortran'], rhs['term_sizes'])]
        result['rhs_worst_relative_error'] = max(result['rhs_relative_errors'])
    result['passed'] = (result['worst_relative_error'] <= DERIVATIVE_TOLERANCE and all(p['ijac_difference'] == 0 for p in points)
                        and (not rhs or result['rhs_worst_relative_error'] <= rhs['relative_tolerance']))
    (folder / 'exact-check.json').write_text(json.dumps(result, indent=2) + '\n')
    return result
