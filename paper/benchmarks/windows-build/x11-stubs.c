/* W244 (#300): the X11 functions (and fork/wait) the pinned XPPAUT 8.0
   links against, for its native Windows benchmark build (build.sh). The
   paper's runs use -silent, which never opens a display; each stub aborts,
   so a run that did reach one fails loudly instead of being timed. The list
   is the link's undefined symbols with no X11 library, nothing more.
   Deliberately unprototyped (no Xlib.h here): the stubs never return. */
#include <stdio.h>
#include <stdlib.h>

static void stub(const char *name) {
  fprintf(stderr, "W244 benchmark build: X11/POSIX stub %s called\n", name);
  abort();
}

